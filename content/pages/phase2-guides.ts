function buildPage(def: GuideDef): ContentPage {
  const faqIds = def.faqs.map((_, index) => `${def.id}-faq-${index + 1}`);

  return {
    id: def.id,
    order: def.order,
    numberLabel: String(def.order),
    slug: def.slug,
    href: def.href,
    navLabel: def.h1,
    categoryLabel: SITE.categoryLabel,
    h1: def.h1,
    heading: def.h1,
    breadcrumbLabel: def.h1,
    infoTopicLabel: def.cardDescription.slice(0, 24),
    infoCategory: def.category,
    infoCardDescription: def.cardDescription,
    intro: [
      def.description,
      introDisclaimer(def.category),
    ],
    hubContextLink: {
      before: "상담 전 전체 흐름은 ",
      anchor: def.hubAnchor,
      after: "에서 확인할 수 있습니다.",
      href: "/",
    },
    publishedAt: INFO_GUIDE_BATCH6_PUBLISHED_AT,
    updatedAt: INFO_GUIDE_BATCH6_PUBLISHED_AT,
    faqIds,
    faqTitle: `${def.h1} 자주 묻는 질문`,
    conclusion: conclusionFor(def.category),
    bodyImage: {
      src: `/images/info/${def.slug}.webp`,
      alt: def.imageAlt,
      width: 1200,
      height: 800,
    },
    repeatImage: null,
    accentColor: "#4A6B7C",
    accentHoverColor: "#3A5663",
    showArticleEyebrow: false,
    showRelatedGuideHeading: false,
    showContentCards: true,
    showFaqHub: false,
    keySummary: def.sections.slice(0, 3).map((section, index) => ({
      numberLabel: `0${index + 1}`,
      title: section.heading.slice(0, 18),
      text: section.answer.slice(0, 80),
    })),
    seo: {
      title: def.h1,
      description: def.cardDescription,
      keywords: def.keywords,
      ogImage: "/images/og/임신중절수술-kakao.png",
      socialImage: "/images/og/임신중절수술-kakao.png",
      category: SITE.categoryLabel,
    },
    clinicRelatedLinks: clinicRelatedLinksFor(def.order),
    officialSources: [
      ...INFO_GUIDE_OFFICIAL_SOURCES,
      {
        organization: "국가법령정보센터",
        title: "의료법·개인정보 보호 관련 법령 확인",
        url: "https://www.law.go.kr",
      },
    ],
    sections: def.sections.map((section, index) => ({
      id: section.id,
      order: index + 1,
      numberLabel: String(index + 1).padStart(2, "0"),
      heading: section.heading,
      decorativeIcon: "",
      layout: (section.bullets ? "checklist" : "prose") as
        | "checklist"
        | "prose",
      directAnswer: section.answer,
      paragraphs: [section.body],
      bullets: section.bullets,
      relatedHref:
        index === def.sections.length - 1
          ? def.relatedCost
            ? ROUTES.cost
            : def.relatedRecovery
              ? ROUTES.recovery
              : def.relatedHospital
                ? ROUTES.hospital
                : ROUTES.infoHub
          : undefined,
      relatedLabel:
        index === def.sections.length - 1
          ? def.relatedCost
            ? "임신중절수술 비용 안내"
            : def.relatedRecovery
              ? "임신중절수술 회복기간 안내"
              : def.relatedHospital
                ? "임신중절수술병원 선택 기준"
                : "임신중절수술 의료정보 전체보기"
          : undefined,
    })),
  };
}

